/** Create data for a course from new-courses.ts, with its own weekly format and details. */
export function newCourseData(c: NewCourse, categoryId: string) {
  return {
    title: c.title,
    slug: c.slug,
    summary: c.summary,
    description: c.description,
    level: c.level,
    ...c.format,
    // The middle of the weekly range times the number of weeks, as the admin form stores it.
    durationHours: Math.round((c.weeks.length * (c.format.weeklyHoursMin + c.format.weeklyHoursMax)) / 2),
    price: c.price,
    discountPrice: c.discountPrice,
    instructorName: c.instructorName,
    instructorTitle: c.instructorTitle,
    instructorBio: c.instructorBio,
    featured: c.featured ?? false,
    published: true,
    categoryId,
    ...courseDetailsData(c.details),
    modules: {
      create: c.weeks.map((week, index) => ({
        title: week.title,
        goal: week.goal,
        position: index,
        lessons: {
          create: week.lessons.map((lesson, lessonIndex) => ({
            title: lesson.title,
            durationMin: lesson.durationMin,
            topics: lesson.topics,
            position: lessonIndex,
          })),
        },
      })),
    },
  };
}
